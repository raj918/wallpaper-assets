    cover = covers.get(cat)
    if cover and cover in walls:
        walls.remove(cover)
        walls.insert(0, cover)
    categoryOrders[cat] = walls
    print(f'Category "{cat}": {len(walls)} wallpapers (Cover: {cover})')

